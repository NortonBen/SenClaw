//! MCP server (`ontology-mcp`) exposing the pipeline as tools over HTTP/SSE —
//! same JSON-RPC-over-SSE shape as the other SenClaw Space Apps. Tools are
//! `ontology_*`. They drive the exact same modules the REST API does.

use crate::api::AppState;
use crate::db::now;
use crate::{llm, mapping, profile as prof, prov, reason, resolve, shacl, tbox};
use axum::{
    extract::State,
    response::sse::{Event, Sse},
    Json,
};
use futures_util::stream::Stream;
