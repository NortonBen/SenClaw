macro_rules! pid {
    ($args:expr) => {
        match $args["projectId"].as_i64() {
            Some(v) => v,
            None => return err("projectId is required".into()),
        }
    };
}

async fn call_tool(state: &Arc<AppState>, name: &str, args: &Value) -> Value {
    match name {
        "ontology_list_projects" => match state
            .db
            .list_projects(&|pid| state.graph_for(pid).map(|g| g.len() as i64).unwrap_or(0))
        {
            Ok(v) => jout(json!(v)),
            Err(e) => err(e.to_string()),
        },
        "ontology_create_project" => {
            let nm = args["name"].as_str().unwrap_or("").trim();
            if nm.is_empty() {
                return err("name is required".into());
            }
            let base = args["baseIri"]
                .as_str()
                .filter(|s| !s.trim().is_empty())
                .map(String::from)
                .unwrap_or_else(|| {
                    format!(
                        "http://senclaw.local/onto/{}/",
                        crate::vocab::encode_segment(nm)
                    )
                });
            match state
                .db
                .create_project(nm, args["description"].as_str().unwrap_or(""), &base)
            {
                Ok(id) => {
                    let ex = format!("{}#", base.trim_end_matches(['/', '#']));
                    let _ = state.db.set_prefixes(id, &json!({ "ex": ex }));
                    jout(json!({ "id": id, "baseIri": base }))
                }
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_source" | "ontology_ingest" => {
            let id = pid!(args);
            let nm = args["name"].as_str().unwrap_or("").trim();
            let content = args["content"].as_str().unwrap_or("");
            if nm.is_empty() || content.is_empty() {
                return err("name and content are required".into());
            }
            // An explicit kind short-circuits detection; otherwise the sniffer
            // decides, so pasting YAML/XML/JSONL/Markdown still works.
            let parts = match args["kind"].as_str().filter(|k| !k.trim().is_empty()) {
                Some(kind) => vec![crate::ingest::Ingested {
                    name: nm.to_string(),
                    kind: kind.to_string(),
                    origin: kind.to_string(),
                    content: content.to_string(),
                    note: String::new(),
                    rows: 0,
                    columns: 0,
                }],
                None => match crate::ingest::ingest_text(nm, content) {
                    Ok(v) => v,
                    Err(e) => return err(e.to_string()),
                },
            };
            let mut out = Vec::new();
            for p in parts {
                let t = match prof::parse(&p.kind, &p.content) {
                    Ok(t) => t,
                    Err(e) => return err(e.to_string()),
                };
                let cols = json!(prof::profile(&t));
                match state.db.add_source(
                    id,
                    &p.name,
                    &p.kind,
                    &p.content,
                    &cols,
                    t.rows.len() as i64,
                    &p.origin,
                    &p.note,
                ) {
                    Ok(sid) => out.push(json!({
                        "sourceId": sid, "name": p.name, "kind": p.kind, "origin": p.origin,
                        "note": p.note, "rowCount": t.rows.len(), "columns": cols
                    })),
                    Err(e) => return err(e.to_string()),
                }
            }
            jout(json!({ "sources": out }))
        }
        "ontology_autobuild" => {
            let id = pid!(args);
            let opts: crate::auto::AutoOpts =
                serde_json::from_value(args.clone()).unwrap_or_default();
            let job = crate::auto::start(state.clone(), id, opts);
            jout(json!({
                "jobId": job,
                "note": "Autobuild is running in the background. Poll ontology_autobuild_status with this jobId."
            }))
        }
        "ontology_autobuild_status" => {
            let job = args["jobId"].as_str().unwrap_or("");
            let handle = state.jobs.lock().unwrap().get(job).cloned();
            match handle {
                Some(h) => {
                    let snap = h.lock().unwrap().clone();
                    match serde_json::to_value(snap) {
                        Ok(v) => jout(v),
                        Err(e) => err(e.to_string()),
                    }
                }
                None => err(format!("no such job: {job}")),
            }
        }
        "ontology_ask" => {
            let id = pid!(args);
            match crate::auto::ask(state, id, args["question"].as_str().unwrap_or("")).await {
                Ok(v) => jout(v),
                Err(e) => err(e),
            }
        }
        "ontology_create_function" => {
            let id = pid!(args);
            let name = args["name"].as_str().unwrap_or("").trim();
            if name.is_empty() {
                return err("name is required".into());
            }
            let kind = match args["kind"].as_str() {
                Some("classify") => "classify",
                Some("resolve") => "resolve",
                _ => "extract",
            };
            let input_kind = match kind {
                "classify" => "source",
                "resolve" => "class",
                _ => "text",
            };
            match state.db.create_function(
                id,
                name,
                kind,
                input_kind,
                args["target"].as_str().unwrap_or(""),
                args["instruction"].as_str().unwrap_or(""),
                args["autoApply"].as_bool().unwrap_or(false),
            ) {
                Ok(fid) => jout(json!({ "functionId": fid, "kind": kind })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_list_functions" => {
            let id = pid!(args);
            match (state.db.list_functions(id), state.db.proposal_counts(id)) {
                (Ok(f), Ok(c)) => jout(json!({ "functions": f, "proposalCounts": c })),
                (Err(e), _) | (_, Err(e)) => err(e.to_string()),
            }
        }
        "ontology_run_function" | "ontology_trial_function" => {
            let id = pid!(args);
            let Some(fid) = args["functionId"].as_i64() else {
                return err("functionId is required".into());
            };
            let trial = name == "ontology_trial_function";
            match crate::logic::run(state, id, fid, trial).await {
                Ok(rep) => jout(serde_json::to_value(rep).unwrap_or_default()),
                Err(e) => err(e),
            }
        }
        "ontology_list_proposals" => {
            let id = pid!(args);
            let status = args["status"].as_str();
            match (
                state.db.list_proposals(id, status),
                state.db.proposal_counts(id),
            ) {
                (Ok(p), Ok(c)) => jout(json!({ "proposals": p, "counts": c })),
                (Err(e), _) | (_, Err(e)) => err(e.to_string()),
            }
        }
        "ontology_approve_proposals" => {
            let id = pid!(args);
            let ids: Vec<i64> = args["ids"]
                .as_array()
                .map(|a| a.iter().filter_map(|x| x.as_i64()).collect())
                .unwrap_or_default();
            match crate::logic::approve(state, id, &ids).await {
                Ok(v) => jout(v),
                Err(e) => err(e),
            }
        }
        "ontology_reject_proposals" => {
            let id = pid!(args);
            let ids: Vec<i64> = args["ids"]
                .as_array()
                .map(|a| a.iter().filter_map(|x| x.as_i64()).collect())
                .unwrap_or_default();
            match state.db.reject_proposals(id, &ids) {
                Ok(n) => jout(json!({ "rejected": n })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_assist" => {
            let id = pid!(args);
            let ctx: crate::aip::Context =
                serde_json::from_value(args["context"].clone()).unwrap_or_default();
            match crate::aip::assist(state, id, args["question"].as_str().unwrap_or(""), &ctx).await
            {
                Ok(v) => jout(v),
                Err(e) => err(e),
            }
        }
        "ontology_live_schema" => {
            let id = pid!(args);
            match state.graph_for(id).and_then(|g| tbox::live_schema(&g)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_get_tbox" => {
            let id = pid!(args);
            match state.graph_for(id).and_then(|g| tbox::read(&g)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_class" => {
            let id = pid!(args);
            run_tbox(state, id, args, true).await
        }
        "ontology_add_property" => {
            let id = pid!(args);
            run_tbox(state, id, args, false).await
        }
        "ontology_apply_tbox" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) {
                Ok(v) => v,
                Err(e) => return err(e.to_string()),
            };
            let draft: tbox::TboxDraft = match serde_json::from_value(args["draft"].clone()) {
                Ok(d) => d,
                Err(e) => return err(format!("invalid draft: {e}")),
            };
            let g = match state.graph_for(id) {
                Ok(g) => g,
                Err(e) => return err(e.to_string()),
            };
            match tbox::apply_draft(&g, &base, &pfx, &draft) {
                Ok((nc, np)) => {
                    if !draft.prefixes.is_empty() {
                        let mut m = pfx.clone();
                        m.extend(draft.prefixes.clone());
                        let _ = state.db.set_prefixes(id, &json!(m));
                    }
                    let _ = state.persist(id, &g);
                    jout(json!({ "classes": nc, "properties": np }))
                }
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_set_mapping" => {
            let id = pid!(args);
            let m = args["mapping"].clone();
            if serde_json::from_value::<mapping::Mapping>(m.clone()).is_err() {
                return err("invalid mapping DSL".into());
            }
            match state.db.set_mapping(id, &m) {
                Ok(()) => jout(json!({ "ok": true })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_preview_mapping" | "ontology_lift" => {
            let id = pid!(args);
            run_lift(state, id, args, name == "ontology_lift").await
        }
        "ontology_sparql" => {
            let id = pid!(args);
            let q = args["query"].as_str().unwrap_or("");
            let pfx = state.ctx(id).map(|(_, p)| p).unwrap_or_default();
            match state
                .graph_for(id)
                .and_then(|g| g.query_json(&crate::vocab::ensure_prefixes(q, &pfx)))
            {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_competency" => {
            let id = pid!(args);
            match state.db.add_cq(
                id,
                args["question"].as_str().unwrap_or(""),
                args["sparql"].as_str().unwrap_or(""),
                args["expect"].as_str().unwrap_or("nonempty"),
            ) {
                Ok(cid) => jout(json!({ "id": cid })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_run_competency" => {
            let id = pid!(args);
            run_competency(state, id)
        }
        "ontology_set_shapes" => {
            let id = pid!(args);
            let sh = args["shapes"].clone();
            if serde_json::from_value::<shacl::Shapes>(sh.clone()).is_err() {
                return err("invalid shapes".into());
            }
            match state.db.set_shapes(id, &sh) {
                Ok(()) => jout(json!({ "ok": true })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_validate" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) {
                Ok(v) => v,
                Err(e) => return err(e.to_string()),
            };
            let raw = if args["shapes"].is_object() {
                args["shapes"].clone()
            } else {
                state.db.get_shapes(id).unwrap_or(json!({"nodeShapes":[]}))
            };
            let shapes: shacl::Shapes = match serde_json::from_value(raw) {
                Ok(s) => s,
                Err(e) => return err(e.to_string()),
            };
            match state
                .graph_for(id)
                .and_then(|g| shacl::validate(&g, &base, &pfx, &shapes))
            {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_materialize" => {
            let id = pid!(args);
            match state.graph_for(id) {
                Ok(g) => match reason::materialize(&g) {
                    Ok(rep) => {
                        let _ = state.persist(id, &g);
                        jout(rep)
                    }
                    Err(e) => err(e.to_string()),
                },
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_resolve_candidates" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) {
                Ok(v) => v,
                Err(e) => return err(e.to_string()),
            };
            let class = args["class"].as_str().unwrap_or("");
            let lp = args["labelProp"].as_str().unwrap_or("rdfs:label");
            let th = args["threshold"].as_f64().unwrap_or(0.9);
            match state
                .graph_for(id)
                .and_then(|g| resolve::candidates(&g, &base, &pfx, class, lp, th))
            {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_list_batches" => {
            let id = pid!(args);
            match state.graph_for(id).and_then(|g| prov::list_batches(&g)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_drop_batch" => {
            let id = pid!(args);
            let iri = args["iri"].as_str().unwrap_or("");
            match state.graph_for(id) {
                Ok(g) => match prov::drop_batch(&g, iri) {
                    Ok(()) => {
                        let _ = state.persist(id, &g);
                        jout(json!({ "ok": true }))
                    }
                    Err(e) => err(e.to_string()),
                },
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_extract" => {
            let id = pid!(args);
            run_extract(state, id, args).await
        }
        _ => err(format!("Unknown tool: {name}")),
    }
}

async fn run_tbox(state: &Arc<AppState>, id: i64, args: &Value, is_class: bool) -> Value {
    let (base, pfx) = match state.ctx(id) {
        Ok(v) => v,
        Err(e) => return err(e.to_string()),
    };
    let g = match state.graph_for(id) {
        Ok(g) => g,
        Err(e) => return err(e.to_string()),
    };
    let res = if is_class {
        serde_json::from_value::<tbox::ClassDef>(args.clone())
            .map_err(|e| e.to_string())
            .and_then(|d| tbox::add_class(&g, &base, &pfx, &d).map_err(|e| e.to_string()))
    } else {
        serde_json::from_value::<tbox::PropertyDef>(args.clone())
            .map_err(|e| e.to_string())
            .and_then(|d| tbox::add_property(&g, &base, &pfx, &d).map_err(|e| e.to_string()))
    };
    match res {
        Ok(iri) => {
            let _ = state.persist(id, &g);
            jout(json!({ "iri": iri }))
        }
        Err(e) => err(e),
    }
}

async fn run_lift(state: &Arc<AppState>, id: i64, args: &Value, write: bool) -> Value {
    let (base, _pfx) = match state.ctx(id) {
        Ok(v) => v,
        Err(e) => return err(e.to_string()),
    };
    let raw = if args["mapping"].is_object() {
        args["mapping"].clone()
    } else {
        state.db.get_mapping(id).unwrap_or(json!({}))
    };
    let m: mapping::Mapping = match serde_json::from_value(raw) {
        Ok(m) => m,
        Err(e) => return err(format!("invalid mapping: {e}")),
    };
    // Resolve sources.
    let mut sources: HashMap<String, prof::Table> = HashMap::new();
    for tm in &m.triples_maps {
        if sources.contains_key(&tm.source) {
            continue;
        }
        match state.db.source_by_name(id, &tm.source) {
            Ok(Some((kind, content))) => match prof::parse(&kind, &content) {
                Ok(t) => {
                    sources.insert(tm.source.clone(), t);
                }
                Err(e) => return err(e.to_string()),
            },
            _ => return err(format!("source '{}' not uploaded", tm.source)),
        }
    }
    let g = match state.graph_for(id) {
        Ok(g) => g,
        Err(e) => return err(e.to_string()),
    };
    if write {
        let ts = now();
        let label = m
            .triples_maps
            .first()
            .map(|t| t.source.clone())
            .unwrap_or_else(|| "import".into());
        let batch = prov::batch_iri(ts, &label);
        match mapping::lift(&g, &m, &sources, &base, &batch) {
            Ok(rep) => {
                let _ = prov::record_batch(&g, &batch, &label, &label, "lift", rep.triples, ts);
                let _ = state.persist(id, &g);
                jout(
                    json!({ "batch": batch, "triples": rep.triples, "subjects": rep.subjects, "skippedRows": rep.skipped_rows, "totalTriples": g.len() }),
                )
            }
            Err(e) => err(e.to_string()),
        }
    } else {
        match mapping::preview(&m, &sources, &base, 25) {
            Ok(rep) => jout(json!({
                "triples": rep.triples, "subjects": rep.subjects, "skippedRows": rep.skipped_rows,
                "samples": rep.samples.iter().map(|(a,b,c)| json!([a,b,c])).collect::<Vec<_>>(),
            })),
            Err(e) => err(e.to_string()),
        }
    }
}

fn run_competency(state: &Arc<AppState>, id: i64) -> Value {
    let g = match state.graph_for(id) {
        Ok(g) => g,
        Err(e) => return err(e.to_string()),
    };
    let pfx = state.ctx(id).map(|(_, p)| p).unwrap_or_default();
    let cqs = match state.db.list_cq(id) {
        Ok(v) => v,
        Err(e) => return err(e.to_string()),
    };
    let mut results = Vec::new();
    let mut passed = 0;
    for cq in &cqs {
        if cq.sparql.trim().is_empty() {
            results.push(json!({ "question": cq.question, "pass": false, "error": "no SPARQL" }));
            continue;
        }
        match g.query_json(&crate::vocab::ensure_prefixes(&cq.sparql, &pfx)) {
            Ok(res) => {
                let count = res["rows"].as_array().map(|a| a.len()).unwrap_or(0);
                let pass = match cq.expect.as_str() {
                    "empty" => count == 0,
                    "boolean" => res["boolean"].as_bool().unwrap_or(false),
                    _ => count > 0 || res["boolean"].as_bool().unwrap_or(false),
                };
                if pass {
                    passed += 1;
                }
                results.push(json!({ "question": cq.question, "pass": pass, "count": count }));
            }
            Err(e) => results
                .push(json!({ "question": cq.question, "pass": false, "error": e.to_string() })),
        }
    }
    jout(json!({ "total": cqs.len(), "passed": passed, "results": results }))
}

async fn run_extract(state: &Arc<AppState>, id: i64, args: &Value) -> Value {
    let (base, pfx) = match state.ctx(id) {
        Ok(v) => v,
        Err(e) => return err(e.to_string()),
    };
    let txt = args["text"].as_str().unwrap_or("");
    if txt.trim().is_empty() {
        return err("text is required".into());
    }
    let g = match state.graph_for(id) {
        Ok(g) => g,
        Err(e) => return err(e.to_string()),
    };
    let tb = tbox::read(&g).unwrap_or(json!({}));
    let max_chunks = args["maxChunks"].as_u64().unwrap_or(12) as usize;
    let (triples, model, chunks, errors) =
        match llm::extract_triples_chunked(txt, &tb, max_chunks).await {
            Ok(v) => v,
            Err(e) => return err(e),
        };
    let label = args["label"].as_str().unwrap_or("text extraction");
    match crate::auto::insert_extracted(state, id, &g, label, &triples, &base, &pfx) {
        Ok(inserted) => jout(
            json!({ "inserted": inserted, "model": model, "chunks": chunks, "errors": errors }),
        ),
        Err(e) => err(e),
    }
}
