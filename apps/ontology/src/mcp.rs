macro_rules! pid {
    ($args:expr) => {
        match $args["projectId"].as_i64() {
            Some(v) => v,
            None => return err("projectId is required".into()),
        }
    };
}

async fn call_tool(state: &Arc<AppState>, name: &str, args: &Value) -> Value {
    match name {
        "ontology_list_projects" => match state.db.list_projects(&|pid| state.graph_for(pid).map(|g| g.len() as i64).unwrap_or(0)) {
            Ok(v) => jout(json!(v)),
            Err(e) => err(e.to_string()),
        },
        "ontology_create_project" => {
            let nm = args["name"].as_str().unwrap_or("").trim();
            if nm.is_empty() {
                return err("name is required".into());
            }
            let base = args["baseIri"].as_str().filter(|s| !s.trim().is_empty()).map(String::from)
                .unwrap_or_else(|| format!("http://senclaw.local/onto/{}/", crate::vocab::encode_segment(nm)));
            match state.db.create_project(nm, args["description"].as_str().unwrap_or(""), &base) {
                Ok(id) => {
                    let ex = format!("{}#", base.trim_end_matches(['/', '#']));
                    let _ = state.db.set_prefixes(id, &json!({ "ex": ex }));
                    jout(json!({ "id": id, "baseIri": base }))
                }
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_source" => {
            let id = pid!(args);
            let nm = args["name"].as_str().unwrap_or("").trim();
            let content = args["content"].as_str().unwrap_or("");
            if nm.is_empty() || content.is_empty() {
                return err("name and content are required".into());
            }
            let kind = args["kind"].as_str().unwrap_or(if nm.ends_with(".json") { "json" } else { "csv" });
            match prof::parse(kind, content) {
                Ok(t) => {
                    let cols = json!(prof::profile(&t));
                    match state.db.add_source(id, nm, kind, content, &cols, t.rows.len() as i64) {
                        Ok(sid) => jout(json!({ "sourceId": sid, "rowCount": t.rows.len(), "columns": cols })),
                        Err(e) => err(e.to_string()),
                    }
                }
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_get_tbox" => {
            let id = pid!(args);
            match state.graph_for(id).and_then(|g| tbox::read(&g)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_class" => {
            let id = pid!(args);
            run_tbox(state, id, args, true).await
        }
        "ontology_add_property" => {
            let id = pid!(args);
            run_tbox(state, id, args, false).await
        }
        "ontology_apply_tbox" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
            let draft: tbox::TboxDraft = match serde_json::from_value(args["draft"].clone()) {
                Ok(d) => d, Err(e) => return err(format!("invalid draft: {e}")),
            };
            let g = match state.graph_for(id) { Ok(g) => g, Err(e) => return err(e.to_string()) };
            match tbox::apply_draft(&g, &base, &pfx, &draft) {
                Ok((nc, np)) => {
                    if !draft.prefixes.is_empty() {
                        let mut m = pfx.clone(); m.extend(draft.prefixes.clone());
                        let _ = state.db.set_prefixes(id, &json!(m));
                    }
                    let _ = state.persist(id, &g);
                    jout(json!({ "classes": nc, "properties": np }))
                }
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_set_mapping" => {
            let id = pid!(args);
            let m = args["mapping"].clone();
            if serde_json::from_value::<mapping::Mapping>(m.clone()).is_err() {
                return err("invalid mapping DSL".into());
            }
            match state.db.set_mapping(id, &m) {
                Ok(()) => jout(json!({ "ok": true })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_preview_mapping" | "ontology_lift" => {
            let id = pid!(args);
            run_lift(state, id, args, name == "ontology_lift").await
        }
        "ontology_sparql" => {
            let id = pid!(args);
            let q = args["query"].as_str().unwrap_or("");
            let pfx = state.ctx(id).map(|(_, p)| p).unwrap_or_default();
            match state.graph_for(id).and_then(|g| g.query_json(&crate::vocab::ensure_prefixes(q, &pfx))) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_add_competency" => {
            let id = pid!(args);
            match state.db.add_cq(id, args["question"].as_str().unwrap_or(""), args["sparql"].as_str().unwrap_or(""), args["expect"].as_str().unwrap_or("nonempty")) {
                Ok(cid) => jout(json!({ "id": cid })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_run_competency" => {
            let id = pid!(args);
            run_competency(state, id)
        }
        "ontology_set_shapes" => {
            let id = pid!(args);
            let sh = args["shapes"].clone();
            if serde_json::from_value::<shacl::Shapes>(sh.clone()).is_err() {
                return err("invalid shapes".into());
            }
            match state.db.set_shapes(id, &sh) {
                Ok(()) => jout(json!({ "ok": true })),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_validate" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
            let raw = if args["shapes"].is_object() { args["shapes"].clone() } else { state.db.get_shapes(id).unwrap_or(json!({"nodeShapes":[]})) };
            let shapes: shacl::Shapes = match serde_json::from_value(raw) { Ok(s) => s, Err(e) => return err(e.to_string()) };
            match state.graph_for(id).and_then(|g| shacl::validate(&g, &base, &pfx, &shapes)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_materialize" => {
            let id = pid!(args);
            match state.graph_for(id) {
                Ok(g) => match reason::materialize(&g) {
                    Ok(rep) => { let _ = state.persist(id, &g); jout(rep) }
                    Err(e) => err(e.to_string()),
                },
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_resolve_candidates" => {
            let id = pid!(args);
            let (base, pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
            let class = args["class"].as_str().unwrap_or("");
            let lp = args["labelProp"].as_str().unwrap_or("rdfs:label");
            let th = args["threshold"].as_f64().unwrap_or(0.9);
            match state.graph_for(id).and_then(|g| resolve::candidates(&g, &base, &pfx, class, lp, th)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_list_batches" => {
            let id = pid!(args);
            match state.graph_for(id).and_then(|g| prov::list_batches(&g)) {
                Ok(v) => jout(v),
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_drop_batch" => {
            let id = pid!(args);
            let iri = args["iri"].as_str().unwrap_or("");
            match state.graph_for(id) {
                Ok(g) => match prov::drop_batch(&g, iri) {
                    Ok(()) => { let _ = state.persist(id, &g); jout(json!({ "ok": true })) }
                    Err(e) => err(e.to_string()),
                },
                Err(e) => err(e.to_string()),
            }
        }
        "ontology_extract" => {
            let id = pid!(args);
            run_extract(state, id, args).await
        }
        _ => err(format!("Unknown tool: {name}")),
    }
}

async fn run_tbox(state: &Arc<AppState>, id: i64, args: &Value, is_class: bool) -> Value {
    let (base, pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
    let g = match state.graph_for(id) { Ok(g) => g, Err(e) => return err(e.to_string()) };
    let res = if is_class {
        serde_json::from_value::<tbox::ClassDef>(args.clone()).map_err(|e| e.to_string())
            .and_then(|d| tbox::add_class(&g, &base, &pfx, &d).map_err(|e| e.to_string()))
    } else {
        serde_json::from_value::<tbox::PropertyDef>(args.clone()).map_err(|e| e.to_string())
            .and_then(|d| tbox::add_property(&g, &base, &pfx, &d).map_err(|e| e.to_string()))
    };
    match res {
        Ok(iri) => { let _ = state.persist(id, &g); jout(json!({ "iri": iri })) }
        Err(e) => err(e),
    }
}

async fn run_lift(state: &Arc<AppState>, id: i64, args: &Value, write: bool) -> Value {
    let (base, _pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
    let raw = if args["mapping"].is_object() { args["mapping"].clone() } else { state.db.get_mapping(id).unwrap_or(json!({})) };
    let m: mapping::Mapping = match serde_json::from_value(raw) { Ok(m) => m, Err(e) => return err(format!("invalid mapping: {e}")) };
    // Resolve sources.
    let mut sources: HashMap<String, prof::Table> = HashMap::new();
    for tm in &m.triples_maps {
        if sources.contains_key(&tm.source) { continue; }
        match state.db.source_by_name(id, &tm.source) {
            Ok(Some((kind, content))) => match prof::parse(&kind, &content) {
                Ok(t) => { sources.insert(tm.source.clone(), t); }
                Err(e) => return err(e.to_string()),
            },
            _ => return err(format!("source '{}' not uploaded", tm.source)),
        }
    }
    let g = match state.graph_for(id) { Ok(g) => g, Err(e) => return err(e.to_string()) };
    if write {
        let ts = now();
        let label = m.triples_maps.first().map(|t| t.source.clone()).unwrap_or_else(|| "import".into());
        let batch = prov::batch_iri(ts, &label);
        match mapping::lift(&g, &m, &sources, &base, &batch) {
            Ok(rep) => {
                let _ = prov::record_batch(&g, &batch, &label, &label, "lift", rep.triples, ts);
                let _ = state.persist(id, &g);
                jout(json!({ "batch": batch, "triples": rep.triples, "subjects": rep.subjects, "skippedRows": rep.skipped_rows, "totalTriples": g.len() }))
            }
            Err(e) => err(e.to_string()),
        }
    } else {
        match mapping::preview(&m, &sources, &base, 25) {
            Ok(rep) => jout(json!({
                "triples": rep.triples, "subjects": rep.subjects, "skippedRows": rep.skipped_rows,
                "samples": rep.samples.iter().map(|(a,b,c)| json!([a,b,c])).collect::<Vec<_>>(),
            })),
            Err(e) => err(e.to_string()),
        }
    }
}

fn run_competency(state: &Arc<AppState>, id: i64) -> Value {
    let g = match state.graph_for(id) { Ok(g) => g, Err(e) => return err(e.to_string()) };
    let pfx = state.ctx(id).map(|(_, p)| p).unwrap_or_default();
    let cqs = match state.db.list_cq(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
    let mut results = Vec::new();
    let mut passed = 0;
    for cq in &cqs {
        if cq.sparql.trim().is_empty() {
            results.push(json!({ "question": cq.question, "pass": false, "error": "no SPARQL" }));
            continue;
        }
        match g.query_json(&crate::vocab::ensure_prefixes(&cq.sparql, &pfx)) {
            Ok(res) => {
                let count = res["rows"].as_array().map(|a| a.len()).unwrap_or(0);
                let pass = match cq.expect.as_str() {
                    "empty" => count == 0,
                    "boolean" => res["boolean"].as_bool().unwrap_or(false),
                    _ => count > 0 || res["boolean"].as_bool().unwrap_or(false),
                };
                if pass { passed += 1; }
                results.push(json!({ "question": cq.question, "pass": pass, "count": count }));
            }
            Err(e) => results.push(json!({ "question": cq.question, "pass": false, "error": e.to_string() })),
        }
    }
    jout(json!({ "total": cqs.len(), "passed": passed, "results": results }))
}

async fn run_extract(state: &Arc<AppState>, id: i64, args: &Value) -> Value {
    let (base, pfx) = match state.ctx(id) { Ok(v) => v, Err(e) => return err(e.to_string()) };
    let txt = args["text"].as_str().unwrap_or("");
    if txt.trim().is_empty() {
        return err("text is required".into());
    }
    let g = match state.graph_for(id) { Ok(g) => g, Err(e) => return err(e.to_string()) };
    let tb = tbox::read(&g).unwrap_or(json!({}));
    let (extracted, model) = match llm::extract_triples(txt, &tb).await {
        Ok(v) => v, Err(e) => return err(e),
    };
    let ts = now();
    let batch = prov::batch_iri(ts, "text-extract");
    let mut body = String::new();
    let mut inserted = 0;
    if let Some(arr) = extracted["triples"].as_array() {
        for t in arr {
            let (s_raw, p_raw, o_raw) = (t["s"].as_str().unwrap_or(""), t["p"].as_str().unwrap_or(""), t["o"].as_str().unwrap_or(""));
            if s_raw.is_empty() || p_raw.is_empty() || o_raw.is_empty() { continue; }
            let subj = mint(s_raw, &base, &pfx);
            let pred = crate::vocab::expand(p_raw, &pfx, &base);
            let (Some(st), Some(pt)) = (crate::vocab::iri_term(&subj), crate::vocab::iri_term(&pred)) else { continue };
            let obj = if t["oIsLiteral"].as_bool().unwrap_or(true) {
                format!("\"{}\"", crate::vocab::escape_literal(o_raw))
            } else {
                match crate::vocab::iri_term(&mint(o_raw, &base, &pfx)) { Some(x) => x, None => continue }
            };
            body.push_str(&format!("{st} {pt} {obj} .\n"));
            inserted += 1;
        }
    }
    if inserted > 0 {
        if g.update(&format!("INSERT DATA {{ GRAPH <{batch}> {{\n{body}}} }}")).is_ok() {
            let _ = prov::record_batch(&g, &batch, "text extraction", "unstructured text (LLM)", "extract", inserted, ts);
            let _ = state.persist(id, &g);
        }
    }
    jout(json!({ "inserted": inserted, "model": model, "batch": batch }))
}

fn mint(raw: &str, base: &str, pfx: &HashMap<String, String>) -> String {
    let r = raw.trim();
    if r.starts_with("http://") || r.starts_with("https://") || r.starts_with("urn:") || r.contains(':') {
        crate::vocab::expand(r, pfx, base)
    } else {
        crate::vocab::hashed_iri(base, "entity", &[r])
    }
}
