export type DictKey = keyof (typeof DICT)['vi']
export type T = (k: DictKey) => string

export function makeT(lang: Lang): T {
  const table = DICT[lang]
  return (k: DictKey) => table[k] ?? DICT.vi[k] ?? k
}

/// Look up a dynamic `<prefix>_<value>` key (role_lead, orgKind_partner, …).
/// Falls back to the raw value when the enum grew a member the dict has not
/// caught up with — better a bare `foo` in the UI than a crash.
export function tk(t: T, prefix: string, value: string): string {
  const key = `${prefix}_${value}` as DictKey
  const out = t(key)
  return out === key ? value : out
}

/// `{a}`/`{b}`/`{c}` interpolation for the handful of strings that carry numbers.
export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}
